import Markdown, { CopyButton } from "./Markdown.jsx";
import { RefreshIcon } from "./Icons.jsx";

function MetaLine({ m }) {
  const hit = m.resolution_source === "LLM_CACHE";
  const answeredBy = hit
    ? "from cache"
    : `${m.key_id}${m.fallback_attempts > 0 ? ` · after ${m.fallback_attempts} failed ${m.fallback_attempts === 1 ? "key" : "keys"}` : ""}`;
  return (
    <div className="meta" aria-label="Response details">
      <span className={`meta-source ${hit ? "is-cache" : "is-live"}`} data-testid="meta-source"
        title={hit ? "Served from the response cache" : "Generated by the model"}>{m.resolution_source}</span>
      <span className="meta-sep" aria-hidden="true">·</span>
      <span className="meta-model" data-testid="meta-model">{m.model}</span>
      <span className="meta-break" aria-hidden="true" />
      <span className="meta-stat"><span data-testid="meta-latency">{m.latency_ms} ms</span></span>
      <span className="meta-stat"><span data-testid="meta-input-tokens">{m.input_tokens}</span> input tokens</span>
      <span className="meta-stat"><span data-testid="meta-output-tokens">{m.output_tokens}</span> output tokens</span>
      <span className="meta-stat meta-by">{answeredBy}</span>
    </div>
  );
}

export default function Message({ msg, onRetry, busy }) {
  if (msg.role === "user") {
    return (
      <div className="turn turn-user">
        <div className="user-bubble">{msg.content}</div>
      </div>
    );
  }
  if (msg.role === "error") {
    return (
      <div className="turn">
        <div className="notice" role="alert">
          <p>{msg.content}</p>
          {msg.retryText && (
            <button type="button" className="btn" onClick={() => onRetry(msg)} disabled={busy}>
              <RefreshIcon />Try again
            </button>
          )}
        </div>
      </div>
    );
  }
  return (
    <div className="turn">
      <article className="assistant" data-testid="assistant-message">
        <Markdown>{msg.content}</Markdown>
        <div className="assistant-foot">
          <MetaLine m={msg.meta} />
          <CopyButton text={msg.content} label="Copy" className="reply-copy" />
        </div>
      </article>
    </div>
  );
}
